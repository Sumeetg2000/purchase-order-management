const CHECK_VIOLATION = '23514';
const UNIQUE_VIOLATION = '23505';
const INSUFFICIENT_PRIVILEGE = '42501';
const ACTOR_CONTEXT_REQUIRED = 'PO001';

async function database(): Promise<TestDatabase> {
  return trackDatabase(await createTestDatabase());
}

/** Runs one statement as po_app in a transaction with a SYSTEM actor context. */
async function asApp(client: pg.Client, sql: string, params: unknown[] = []) {
  await client.query('BEGIN');
  try {
    await client.query(`SELECT set_config('app.actor_txid', txid_current()::text, true)`);
    await client.query(`SELECT set_config('app.actor_type', 'SYSTEM', true)`);
    const result = await client.query<Record<string, unknown>>(sql, params);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  }
}

async function sqlstate(run: () => Promise<unknown>): Promise<string | undefined> {
  try {
    await run();
    return undefined;
  } catch (error) {
    return (error as { code?: string }).code;
  }
}

interface VendorRow {
  name: string;
  contact_name: string;
  contact_email: string;
  contact_phone: string | null;
  payment_term_type: string;
  net_days: number | null;
  advance_percent: number | null;
}

const valid: VendorRow = {
  name: 'Acme Supplies',
  contact_name: 'Ravi Shah',
  contact_email: 'ravi@acme.example',
  contact_phone: '+91 (22) 4000-1000',
  payment_term_type: 'NET',
  net_days: 30,
  advance_percent: null,
};

function insertVendor(client: pg.Client, row: Partial<VendorRow> = {}) {
  const v = { ...valid, ...row };
  return asApp(
    client,
    `INSERT INTO vendors (name, contact_name, contact_email, contact_phone,
                          payment_term_type, net_days, advance_percent)
     VALUES ($1, $2, $3, $4, $5, $6, $7) RETURNING id, name_key, status, version`,
    [
      v.name,
      v.contact_name,
      v.contact_email,
      v.contact_phone,
      v.payment_term_type,
      v.net_days,
      v.advance_percent,
    ],
  );
}

describe('[FR-VEN-01] vendors table (0011)', () => {
  it('[FR-VEN-01] has the data-model columns and nothing else', async () => {
    const admin = await (await database()).client('postgres');
    const { rows } = await admin.query<{ col: string }>(
      `SELECT column_name || ' ' || data_type || ' ' ||
              CASE is_nullable WHEN 'YES' THEN 'NULL' ELSE 'NOT NULL' END AS col
         FROM information_schema.columns WHERE table_name = 'vendors'
        ORDER BY ordinal_position`,
    );
    expect(rows.map((r) => r.col)).toEqual([
      'id uuid NOT NULL',
      'name text NOT NULL',
      'name_key text NULL',
      'contact_name text NOT NULL',
      'contact_email text NOT NULL',
      'contact_phone text NULL',
      'payment_term_type text NOT NULL',
      'net_days smallint NULL',
      'advance_percent smallint NULL',
      'status text NOT NULL',
      'deactivated_at timestamp with time zone NULL',
      'version integer NOT NULL',
      'created_at timestamp with time zone NOT NULL',
      'updated_at timestamp with time zone NOT NULL',
    ]);
  });

  it('[FR-VEN-01] name_key is generated by vendor_name_key, stored, in the "C" collation and normalises case, spaces and NFC', async () => {
    const db = await database();
    const admin = await db.client('postgres');
    const { rows: expression } = await admin.query<{ def: string }>(
      `SELECT pg_get_expr(d.adbin, d.adrelid) AS def
         FROM pg_attrdef d JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
        WHERE d.adrelid = 'vendors'::regclass AND a.attname = 'name_key'`,
    );
    expect(expression).toEqual([{ def: 'vendor_name_key(name)' }]);
    const { rows } = await admin.query<{ generated: string; collation: string }>(
      `SELECT attgenerated AS generated, collname AS collation
         FROM pg_attribute a JOIN pg_collation c ON c.oid = a.attcollation
        WHERE attrelid = 'vendors'::regclass AND attname = 'name_key'`,
    );
    expect(rows).toEqual([{ generated: 's', collation: 'C' }]);

    const app = await db.client('po_app');
    const inserted = await insertVendor(app, { name: 'ACME \t  Supplies\u00a0Ltd' });
    expect(inserted.rows[0]).toMatchObject({
      name_key: 'acme supplies ltd',
      status: 'ACTIVE',
      version: 1,
    });
    const composed = await insertVendor(app, { name: 'Café Co' });
    expect(composed.rows[0]?.name_key).toBe('café co');
  });

  it('[FR-VEN-01] two names with one normalised key are refused by vendors_name_key_key', async () => {
    const db = await database();
    const app = await db.client('po_app');
    await insertVendor(app, { name: 'Acme Supplies' });
    for (const name of ['acme supplies', ' ACME   SUPPLIES ', 'Acme\tSupplies']) {
      const error = await insertVendor(app, { name }).catch((e: unknown) => e);
      expect(error, name).toMatchObject({
        code: UNIQUE_VIOLATION,
        constraint: 'vendors_name_key_key',
      });
    }
  });

  it('[FR-VEN-01] name and contact name are 1–200 characters', async () => {
    const app = await (await database()).client('po_app');
    expect(await sqlstate(() => insertVendor(app, { name: '' }))).toBe(CHECK_VIOLATION);
    expect(await sqlstate(() => insertVendor(app, { name: 'n'.repeat(201) }))).toBe(
      CHECK_VIOLATION,
    );
    expect(await sqlstate(() => insertVendor(app, { name: 'n'.repeat(200) }))).toBeUndefined();
    expect(await sqlstate(() => insertVendor(app, { name: 'a', contact_name: '' }))).toBe(
      CHECK_VIOLATION,
    );
    expect(
      await sqlstate(() => insertVendor(app, { name: 'b', contact_name: 'c'.repeat(201) })),
    ).toBe(CHECK_VIOLATION);
  });

  it('[FR-VEN-01] name, contact_name and contact_phone are stored trimmed', async () => {
    const app = await (await database()).client('po_app');
    const refused: Partial<VendorRow>[] = [
      { name: ' Acme' },
      { name: 'Acme ' },
      { contact_name: ' Ravi' },
      { contact_name: 'Ravi ' },
      { contact_phone: ' 1' },
      { contact_phone: '1 ' },
    ];
    for (const [i, row] of refused.entries()) {
      expect(
        await sqlstate(() => insertVendor(app, { name: `r${String(i)}`, ...row })),
        JSON.stringify(row),
      ).toBe(CHECK_VIOLATION);
    }
  });

  it('[FR-VEN-01] contact_email is stored lower-case and at most 254 characters', async () => {
    const app = await (await database()).client('po_app');
    expect(
      await sqlstate(() => insertVendor(app, { name: 'a', contact_email: 'Ravi@acme.example' })),
    ).toBe(CHECK_VIOLATION);
    const long = `${'r'.repeat(242)}@acme.example`; // 255 characters
    expect(await sqlstate(() => insertVendor(app, { name: 'b', contact_email: long }))).toBe(
      CHECK_VIOLATION,
    );
    expect(
      await sqlstate(() => insertVendor(app, { name: 'c', contact_email: long.slice(1) })),
    ).toBeUndefined();
  });

  it('[FR-VEN-01] contact_phone is NULL or 1–30 of digits, spaces, + ( ) -, with a digit; never ""', async () => {
    const app = await (await database()).client('po_app');
    const refused = ['', ' ', 'call me', '+() -', '1'.repeat(31), '022 4000 1000 ext'];
    for (const [i, phone] of refused.entries()) {
      expect(
        await sqlstate(() => insertVendor(app, { name: `r${String(i)}`, contact_phone: phone })),
        JSON.stringify(phone),
      ).toBe(CHECK_VIOLATION);
    }
    const accepted = [null, '1', '+91 (22) 4000-1000', '1'.repeat(30)];
    for (const [i, phone] of accepted.entries()) {
      expect(
        await sqlstate(() => insertVendor(app, { name: `a${String(i)}`, contact_phone: phone })),
        JSON.stringify(phone),
      ).toBeUndefined();
    }
  });

  it('[FR-VEN-01] vendors_payment_terms_valid allows exactly the three term shapes', async () => {
    const app = await (await database()).client('po_app');
    type Terms = Pick<VendorRow, 'payment_term_type' | 'net_days' | 'advance_percent'>;
    const terms = (
      payment_term_type: string,
      net_days: number | null,
      advance_percent: number | null,
    ): Terms => ({
      payment_term_type,
      net_days,
      advance_percent,
    });
    const accepted = [
      terms('NET', 0, null),
      terms('NET', 180, null),
      terms('ADVANCE', null, null),
      terms('PARTIAL_ADVANCE', 0, 1),
      terms('PARTIAL_ADVANCE', 180, 99),
    ];
    const refused = [
      terms('NET', null, null),
      terms('NET', -1, null),
      terms('NET', 181, null),
      terms('NET', 30, 10),
      terms('ADVANCE', 0, null),
      terms('ADVANCE', null, 50),
      terms('PARTIAL_ADVANCE', 30, null),
      terms('PARTIAL_ADVANCE', null, 50),
      terms('PARTIAL_ADVANCE', 30, 0),
      terms('PARTIAL_ADVANCE', 30, 100),
      terms('PARTIAL_ADVANCE', 181, 50),
      terms('COD', null, null),
    ];
    for (const [i, t] of accepted.entries()) {
      expect(
        await sqlstate(() => insertVendor(app, { name: `a${String(i)}`, ...t })),
        JSON.stringify(t),
      ).toBeUndefined();
    }
    for (const [i, t] of refused.entries()) {
      const error = await insertVendor(app, { name: `r${String(i)}`, ...t }).catch(
        (e: unknown) => e,
      );
      expect(error, JSON.stringify(t)).toMatchObject({ code: CHECK_VIOLATION });
    }
  });

  it('[FR-VEN-01] status is ACTIVE or INACTIVE, deactivated_at set exactly when INACTIVE, version >= 1', async () => {
    const app = await (await database()).client('po_app');
    const id = String((await insertVendor(app)).rows[0]?.id);
    const update = (set: string) =>
      sqlstate(() => asApp(app, `UPDATE vendors SET ${set} WHERE id = $1`, [id]));
    expect(await update(`status = 'INACTIVE'`)).toBe(CHECK_VIOLATION);
    expect(await update(`deactivated_at = now()`)).toBe(CHECK_VIOLATION);
    expect(await update(`status = 'DELETED', deactivated_at = now()`)).toBe(CHECK_VIOLATION);
    expect(await update(`version = 0`)).toBe(CHECK_VIOLATION);
    expect(await update(`status = 'INACTIVE', deactivated_at = now()`)).toBeUndefined();
    expect(await update(`status = 'ACTIVE', deactivated_at = NULL`)).toBeUndefined();
  });

  it('[FR-VEN-01] an update moves updated_at', async () => {
    const app = await (await database()).client('po_app');
    const id = String((await insertVendor(app)).rows[0]?.id);
    const { rows } = await asApp(
      app,
      `UPDATE vendors SET contact_name = 'Mira Shah', version = version + 1
        WHERE id = $1 RETURNING updated_at > created_at AS moved`,
      [id],
    );
    expect(rows[0]?.moved).toBe(true);
  });

  it('[FR-VEN-01] a vendor change without an actor context is refused', async () => {
    const app = await (await database()).client('po_app');
    const error = await app
      .query(
        `INSERT INTO vendors (name, contact_name, contact_email, payment_term_type, net_days)
         VALUES ('Acme', 'Ravi', 'ravi@acme.example', 'NET', 30)`,
      )
      .catch((e: unknown) => e);
    expect(error).toMatchObject({ code: ACTOR_CONTEXT_REQUIRED });
  });
});

describe('[FR-VEN-01] vendors privileges (0011)', () => {
  const writable = [
    'name',
    'contact_name',
    'contact_email',
    'contact_phone',
    'payment_term_type',
    'net_days',
    'advance_percent',
  ];

  it('[FR-VEN-01] po_app inserts only the editable columns and updates those plus status and version', async () => {
    const admin = await (await database()).client('postgres');
    const { rows } = await admin.query<{ column: string; ins: boolean; upd: boolean }>(
      `SELECT attname AS column,
              has_column_privilege('po_app', 'vendors', attname, 'INSERT') AS ins,
              has_column_privilege('po_app', 'vendors', attname, 'UPDATE') AS upd
         FROM pg_attribute WHERE attrelid = 'vendors'::regclass AND attnum > 0
          AND NOT attisdropped ORDER BY attnum`,
    );
    const inserts = rows.filter((r) => r.ins).map((r) => r.column);
    const updates = rows.filter((r) => r.upd).map((r) => r.column);
    expect(inserts).toEqual(writable);
    expect(updates).toEqual([...writable, 'status', 'deactivated_at', 'version']);
  });

  it('[FR-VEN-01] po_app can read vendors but never delete or truncate them; po_maintenance has nothing', async () => {
    const db = await database();
    const admin = await db.client('postgres');
    const { rows } = await admin.query<Record<string, boolean>>(
      `SELECT has_table_privilege('po_app', 'vendors', 'SELECT') AS app_select,
              has_table_privilege('po_app', 'vendors', 'DELETE') AS app_delete,
              has_table_privilege('po_app', 'vendors', 'TRUNCATE') AS app_truncate,
              has_table_privilege('po_maintenance', 'vendors',
                'SELECT, INSERT, UPDATE, DELETE, TRUNCATE') AS maintenance_any`,
    );
    expect(rows[0]).toEqual({
      app_select: true,
      app_delete: false,
      app_truncate: false,
      maintenance_any: false,
    });

    const app = await db.client('po_app');
    await insertVendor(app);
    expect(await sqlstate(() => asApp(app, 'DELETE FROM vendors'))).toBe(INSUFFICIENT_PRIVILEGE);
    expect(await sqlstate(() => asApp(app, 'TRUNCATE vendors'))).toBe(INSUFFICIENT_PRIVILEGE);
  });

  it('[FR-VEN-01] po_app can never write name_key', async () => {
    const app = await (await database()).client('po_app');
    const id = String((await insertVendor(app)).rows[0]?.id);
    expect(
      await sqlstate(() => asApp(app, `UPDATE vendors SET name_key = 'x' WHERE id = $1`, [id])),
    ).toBeDefined();
    const { rows } = await app.query<{ name_key: string }>(
      'SELECT name_key FROM vendors WHERE id = $1',
      [id],
    );
    expect(rows[0]?.name_key).toBe('acme supplies');
  });
});

describe('[FR-VEN-01] vendor list and history indexes (0011)', () => {
  async function indexDef(client: pg.Client, name: string): Promise<string | undefined> {
    const { rows } = await client.query<{ def: string }>(
      `SELECT regexp_replace(indexdef, '^CREATE (UNIQUE )?INDEX \\S+ ON \\S+ USING btree ', '\\1') AS def
         FROM pg_indexes WHERE indexname = $1`,
      [name],
    );
    return rows[0]?.def;
  }

  it('[FR-VEN-01] the list and history indexes exist with their key order', async () => {
    const admin = await (await database()).client('postgres');
    expect(await indexDef(admin, 'vendors_name_key_key')).toBe('UNIQUE (name_key)');
    expect(await indexDef(admin, 'vendors_status_name_key_idx')).toBe('(status, name_key, id)');
    expect(await indexDef(admin, 'audit_entries_entity_idx')).toBe(
      '(entity_type, entity_id, occurred_at DESC, id DESC)',
    );
  });
});
